#!/usr/bin/env node
// Common Mandarin words for the uncertain-reading mark (PR #67 review,
// ld-4i2; docs/VOICE.md §Uncertain readings): writes
// web/src/script/zh-words.ts. Run by hand, offline from the app:
//
//   npm run pinyin:words [-- --min 1e-6]
//
// The library's word dictionary (pinyin-pro) holds only the words whose
// reading isn't each character's default, so an everyday word read by
// default (再见, 当然, 教练) looked unsettled to the mark. This list is the
// words that can be marked (a character in it has two ordinary readings
// by the prior's ranks), that CC-CEDICT reads one way only, and that are
// common (wordfreq at least `--min`, default 1e-6): each with that reading.
// The mark treats such a word as settled where it stands as a word of the
// segmenter and the reader read it so (zh.ts commonSettled); it never
// changes a reading.
//
// Sources (downloaded once into the gitignored caches, as gen-zh-freq.mjs
// and pinyin-sweep.mjs do): CC-CEDICT (MDBG, CC BY-SA 4.0) and wordfreq's
// Chinese list (Robyn Speer, CC BY-SA 4.0); the table is CC BY-SA 4.0 like
// zh-freq.ts (ZH-FREQ-LICENSE.txt).

import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";
import { WORDFREQ_SHA256, WORDFREQ_URL, cedictEntries, checkSha256, decodeCBpack, freqDir, marked } from "./gen-zh-freq.mjs";
import { loadCedict } from "./pinyin-sweep.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "..", "web", "src", "script", "zh-words.ts");

/** The longest word kept, in characters: the mark's words are short. */
export const MAX_CHARS = 4;

/** Words CC-CEDICT reads one way that a sentence often reads another: a
 *  number and a measure word (一行字 yī háng, a line; CC-CEDICT's 一行 is
 *  the group, xíng). Never settled by the list. */
export const NOT_SETTLED = new Set(["一行"]);

/**
 * The table's entries ("word=reading", simplified spelling, tone marks, a
 * neutral tone bare) from CC-CEDICT's entries, wordfreq's frequencies and
 * the prior's ranks (a character's ordinary readings), sorted. Pure.
 */
export function commonWords(entries, freq, ranks, min) {
  const readings = new Map();
  for (const e of entries) {
    if (e.proper || e.variant || e.bound || e.sc.length < 2 || e.sc.length > MAX_CHARS || NOT_SETTLED.has(e.simp)) continue;
    const simp = e.simp;
    if ((freq.get(simp) ?? 0) < min) continue;
    if (!e.sc.some((c) => (ranks.get(c)?.length ?? 0) > 1)) continue;
    const r = e.syl.map(marked);
    if (r.some((x) => !x)) continue;
    let set = readings.get(simp);
    if (!set) readings.set(simp, (set = new Set()));
    set.add(r.join(" "));
  }
  const out = [];
  // A word CC-CEDICT reads two ways settles nothing.
  for (const [w, set] of readings) if (set.size === 1) out.push(`${w}=${[...set][0]}`);
  return out.sort();
}

async function main() {
  const min = Number(process.argv[process.argv.indexOf("--min") + 1]) || 1e-6;
  const { text, date } = await loadCedict();
  const file = path.join(freqDir(), "wordfreq", "large_zh.msgpack.gz");
  if (!fs.existsSync(file)) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    console.error(`downloading ${WORDFREQ_URL} …`);
    const res = await fetch(WORDFREQ_URL, { redirect: "follow" });
    if (!res.ok) throw new Error(`download failed: ${res.status}`);
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  checkSha256(file, WORDFREQ_SHA256);
  const freq = decodeCBpack(zlib.gunzipSync(fs.readFileSync(file)));
  const { currentPrior } = await import("../web/src/script/zh.ts");
  const words = commonWords(cedictEntries(text), freq, currentPrior().ranks, min);
  const body = [
    "/* Common Mandarin words for the uncertain-reading mark (zh.ts",
    " * uncertainWords): generated by scripts/gen-zh-words.mjs, do not edit.",
    ` * Derived from CC-CEDICT (${date}; MDBG, CC BY-SA 4.0) and wordfreq's`,
    " * Chinese word list (Robyn Speer; data CC BY-SA 4.0): this table is",
    " * under CC BY-SA 4.0, see ZH-FREQ-LICENSE.txt.",
    ` * Words of 2 to ${MAX_CHARS} characters, at least ${min} of wordfreq's words,`,
    " * with a character of two ordinary readings, that CC-CEDICT reads one",
    " * way; keyed by their simplified spelling. */",
    "",
    `export const COMMON_WORDS = ${JSON.stringify(words.join("|"))};`,
    "",
  ].join("\n");
  fs.writeFileSync(OUT, body);
  console.log(`${words.length} words (${(body.length / 1024).toFixed(0)} KB) → ${path.relative(process.cwd(), OUT)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
