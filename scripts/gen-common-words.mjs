#!/usr/bin/env node
// Everyday words of the Latin-script languages (ld-ne0.17; docs/VOICE.md
// §Words in conversation): writes scripts/common-words.mjs. Run by hand,
// offline from the app:
//
//   npm run words:common [-- --top 3000]
//
// A live word check must not score a line in the learner's own language as
// the language they practise (ownLanguageLine in pronunciation-live.mjs),
// and letters can't tell Spanish from English. So each language gets its
// most frequent `--top` words, all from one source and one cut, which is
// what makes the count fair: a word two languages share (no, me, a, come,
// die) is in both lists and settles nothing. Hand-written lists had it in
// one only, and "He comido" read as English.
//
// The languages are content/languages.yaml's Latin-script ones: only those
// can be a learner's native or target language where the word check runs.
//
// Source (downloaded once into the gitignored cache, as gen-zh-freq.mjs
// does): wordfreq's small lists (Robyn Speer, data CC BY-SA 4.0), pinned at
// the commit gen-zh-freq.mjs uses and checked by SHA-256. The table is CC
// BY-SA 4.0 (scripts/COMMON-WORDS-LICENSE.txt). It holds words only, no
// frequencies.

import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";
import { checkSha256, decodeCBpack, freqDir } from "./gen-zh-freq.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "common-words.mjs");
const COMMIT = "912caf64b657478d1dff1138efdc078947d54bb1";
const url = (lang) => `https://github.com/rspeer/wordfreq/raw/${COMMIT}/wordfreq/data/small_${lang}.msgpack.gz`;

/** wordfreq's small list per language, pinned. */
export const COMMON_SOURCES = {
  en: "f94a80cba6a3857b260d0666b5432bb7ea9b85315574dee9c306e87f61298247",
  es: "ff5853040f65bcc9cb3ed3721d1d09d4405389c1741ebbf529612220829ff5af",
  fr: "8fbbf619ff2e6ff5b3d99d41e69c105daf5795771ce8ef36529f210d571abe6e",
  de: "2115b5bb4adb671a3352555a480b9c2f5b03493e9f7e4047997361d62310017a",
  it: "07a4355d735d9cc864ce9fe679d94a13dee4cefa2495b6b013ecdb214b231c66",
  pt: "fe4e551f6da739583d66cd5ef4fca28a1ccfa2ae5a53a5cbf48aa73dd7c91e0c",
  nl: "ae0d64f10e9d11898b2b9481c0b20698ec40c79b8025edfdd70856bd593ad4b0",
  sv: "a7c52a3d3576db1b7d4280be47aafccabdc70f9a56c5a40bc94b9139e271adf6",
};

/** A list entry kept: letters, with apostrophes or hyphens inside (don't,
 *  aujourd'hui). No digits, no symbols. */
const WORD = /^\p{L}[\p{L}\p{M}'-]*$/u;

async function load(lang) {
  const file = path.join(freqDir(), "wordfreq", `small_${lang}.msgpack.gz`);
  if (!fs.existsSync(file)) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    console.error(`downloading ${url(lang)} …`);
    const res = await fetch(url(lang), { redirect: "follow" });
    if (!res.ok) throw new Error(`download failed: ${res.status} ${url(lang)}`);
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  checkSha256(file, COMMON_SOURCES[lang]);
  return decodeCBpack(zlib.gunzipSync(fs.readFileSync(file)));
}

/** The `top` most frequent words of a wordfreq list; ties in the list's
 *  own order (a Map keeps it), so the output is the same on every run. */
export function topWords(freq, top) {
  return [...freq.entries()]
    .filter(([w]) => WORD.test(w))
    .map(([w, f], i) => [w.normalize("NFC").toLowerCase(), f, i])
    .sort((a, b) => b[1] - a[1] || a[2] - b[2])
    .slice(0, top)
    .map(([w]) => w);
}

async function main() {
  const at = process.argv.indexOf("--top");
  const top = at > 0 ? Number(process.argv[at + 1]) : 3000;
  if (!Number.isInteger(top) || top < 100) throw new Error("--top takes a whole number, 100 or more");
  const lines = [];
  for (const lang of Object.keys(COMMON_SOURCES)) {
    const words = topWords(await load(lang), top);
    lines.push(`  ${lang}: ${JSON.stringify(words.join(" "))},`);
    console.error(`${lang}: ${words.length} words`);
  }
  const out = [
    "// GENERATED by scripts/gen-common-words.mjs (npm run words:common). Do not edit.",
    `// The ${top} most frequent words of each Latin-script language, from wordfreq's`,
    "// small lists (Robyn Speer). Data: CC BY-SA 4.0, apart from the AGPL code;",
    "// see scripts/COMMON-WORDS-LICENSE.txt. Words only, most frequent first.",
    "",
    "/** language → its everyday words, space-separated. */",
    "export const COMMON_WORD_LISTS = Object.freeze({",
    ...lines,
    "});",
    "",
  ].join("\n");
  fs.writeFileSync(OUT, out);
  console.error(`wrote ${path.relative(process.cwd(), OUT)} (${(out.length / 1024).toFixed(0)} KB)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
